/**
 * places.json の市区町村（「都道府県 市区町村」。政令市は区まで）が、内水の配信対象か。
 * ★政令市は市の単位で配信されている（例: 「堺市」→「堺市堺区」も対象）。
 */
export function naisuiCovered(muni: string): boolean {
  const [pref, rest = ""] = muni.split(" ");
  return NAISUI_MUNIS.some(
    ([p, m]) => p === pref && (rest === m || (m.endsWith("市") && rest.startsWith(m) && rest.endsWith("区"))),
  );
}
