/** その市区町村が、手元の面で出せる市区町村か */
export function naisuiExtraFor(muni: string): NaisuiExtra | undefined {
  const [pref, rest = ""] = muni.split(" ");
  return NAISUI_EXTRA.find((x) => x.pref === pref && x.muni === rest);
}

